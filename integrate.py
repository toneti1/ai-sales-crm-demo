"""Integration Pipeline Bridge for AI Sales Assistant.

Connects lead-finder JSON output to sales_assistant_generator Python engine
and accumulates results in unified_leads.json (no overwriting).
"""

from __future__ import annotations

import json
import os
import re
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

# Ensure sales_assistant_generator is in path
ROOT_DIR = Path(__file__).resolve().parent
GENERATOR_DIR = ROOT_DIR / "generator"
sys.path.insert(0, str(GENERATOR_DIR))

from sales_assistant_generator.generator import generate_personalized_package


def _clean_name(name: str | None) -> str:
    """Strip branch/location suffixes and formula-injection prefix characters."""
    if not name:
        return "Unknown Business"
    cleaned = name.split("|")[0].strip().lstrip("=+-@\t\r").strip()
    return cleaned or "Unknown Business"


def _clean_email(email: str | None) -> str | None:
    """Normalize public emails extracted from websites."""
    if not email:
        return None
    cleaned = str(email).strip().rstrip("\\/")
    if "@" not in cleaned:
        return None
    return cleaned


def _map_size(size: str | None) -> str | None:
    """Convert lead-finder size buckets to human-readable ranges."""
    mapping = {
        "micro": "1-5 employees",
        "small": "6-20 employees",
        "medium": "21-100 employees",
    }
    return mapping.get(size) if size else None


def map_sector_to_industry(sector: str, category: str | None) -> str:
    """Map free-text sector/category to generator industry vocabulary."""
    combined = f"{sector or ''} {category or ''}".lower()
    if any(k in combined for k in ["dentis", "dient", "odontol", "ortodon", "dental"]):
        return "dentist"
    if any(k in combined for k in ["fontan", "plumb", "plumber"]):
        return "plumber"
    if any(k in combined for k in ["electri"]):
        return "electrician"
    if any(k in combined for k in ["tejad", "cubiert", "roof"]):
        return "roofing"
    return "local service"


def calculate_website_score(facts: Dict[str, Any] | None, seo_fails: List[str]) -> int:
    """Derive a 0-100 website score from technical facts and SEO failures."""
    if not facts:
        return 50
    if facts.get("siteDown"):
        return 10
    score = 100
    if not facts.get("https"):
        score -= 15
    load_time = facts.get("loadTimeMs", 0)
    if load_time > 5000:
        score -= 20
    elif load_time > 3000:
        score -= 10
    if not facts.get("hasContactForm"):
        score -= 10
    if not facts.get("bookingEngine"):
        score -= 10
    if facts.get("mobileOverflow"):
        score -= 15
    score -= min(len(seo_fails) * 5, 20)
    return max(10, min(99, score))


def extract_pain_points(lead: Dict[str, Any]) -> List[str]:
    """Collect pain points from the audit and key technical facts."""
    points: List[str] = []
    audit = lead.get("audit") or {}
    facts = lead.get("facts") or {}

    # Primary source: rule-based audit issues generated by lead-finder.
    for pp in audit.get("painPoints", []):
        issue = pp.get("issue")
        if issue:
            points.append(issue)

    # Secondary: high-signal technical facts that may not be in the audit.
    if not facts.get("bookingEngine") and not facts.get("hasContactForm"):
        points.append("No online booking or request form")
    if facts.get("mobileOverflow"):
        points.append("Weak mobile experience")
    if facts.get("loadTimeMs", 0) > 4000:
        points.append("Slow page load speed")
    if facts.get("siteDown"):
        points.append("Website appears to be down")

    # Case-insensitive deduplication while preserving original casing.
    seen = set()
    deduped: List[str] = []
    for p in points:
        marker = p.lower().strip(" .")
        if marker and marker not in seen:
            deduped.append(p)
            seen.add(marker)

    return deduped if deduped else ["No clear conversion path for visitors"]


def transform_lead(raw_lead: Dict[str, Any]) -> Dict[str, Any]:
    """Convert a raw lead-finder record into the generator input contract."""
    name = _clean_name(raw_lead.get("name"))
    sector = raw_lead.get("sector", "")
    category = raw_lead.get("category")
    industry = map_sector_to_industry(sector, category)
    location = raw_lead.get("city", "")
    website = raw_lead.get("website")
    email = _clean_email(raw_lead.get("email"))
    facts = raw_lead.get("facts")
    seo_fails = raw_lead.get("seoFails", [])

    pain_points = extract_pain_points(raw_lead)
    website_score = calculate_website_score(facts, seo_fails)

    return {
        "companyName": name,
        "industry": industry,
        "location": location,
        "website": website,
        "email": email,
        "painPoints": pain_points,
        "websiteScore": website_score,
        "companySize": _map_size(raw_lead.get("size")),
        "priority": raw_lead.get("priority", "medium"),
        "placeId": raw_lead.get("placeId"),
        "segment": raw_lead.get("segment"),
    }


def process_leads_file(
    input_path: Path,
    output_path: Path,
    save_html_dir: Path | None = None,
    crm_defaults: Dict[str, Any] | None = None,
) -> Dict[str, Any]:
    """Read lead-finder output, generate packages, and accumulate into unified_leads.json."""
    raw_data = json.loads(input_path.read_text(encoding="utf-8"))
    incoming_leads = raw_data.get("leads", [])

    # Load existing cumulative leads from unified_leads.json if it exists.
    existing_leads: List[Dict[str, Any]] = []
    existing_ids: set[str] = set()

    if output_path.exists():
        try:
            existing_payload = json.loads(output_path.read_text(encoding="utf-8"))
            existing_leads = existing_payload.get("leads", [])
            for item in existing_leads:
                pid = item.get("lead", {}).get("placeId")
                name = item.get("lead", {}).get("companyName")
                if pid:
                    existing_ids.add(pid)
                if name:
                    existing_ids.add(name.lower())
        except Exception:
            existing_leads = []

    # Build a lookup of existing leads so we can preserve CRM fields on re-runs.
    existing_by_id: Dict[str, Dict[str, Any]] = {}
    for item in existing_leads:
        pid = item.get("lead", {}).get("placeId")
        name = item.get("lead", {}).get("companyName")
        if pid:
            existing_by_id[pid] = item
        if name:
            existing_by_id[name.lower()] = item

    processed_leads = list(existing_leads)
    new_added = 0

    if save_html_dir:
        save_html_dir.mkdir(parents=True, exist_ok=True)

    default_crm = crm_defaults or {
        "status": "new",
        "notes": "",
        "tags": [],
        "emailSentAt": None,
        "followUpDueAt": None,
        "followUpCount": 0,
        "createdAt": datetime.now(timezone.utc).isoformat(),
    }

    # Backfill missing CRM fields and clean legacy data for all existing leads.
    for item in processed_leads:
        lead_record = item.setdefault("lead", {})
        for key, value in default_crm.items():
            lead_record.setdefault(key, value)
        if lead_record.get("email"):
            lead_record["email"] = _clean_email(lead_record["email"])

    for raw_lead in incoming_leads:
        place_id = raw_lead.get("placeId")
        clean_name = _clean_name(raw_lead.get("name")).lower()

        # Deduplicate by placeId or company name; preserve existing CRM values.
        existing = existing_by_id.get(place_id) if place_id else None
        if not existing and clean_name:
            existing = existing_by_id.get(clean_name)

        if existing:
            # Backfill any missing CRM fields without overwriting existing ones.
            lead_record = existing.setdefault("lead", {})
            for key, value in default_crm.items():
                lead_record.setdefault(key, value)
            continue

        mapped_input = transform_lead(raw_lead)
        package = generate_personalized_package(mapped_input)

        # Enrich the lead record with CRM fields and original identifiers.
        package["lead"]["priority"] = mapped_input["priority"]
        package["lead"]["placeId"] = mapped_input["placeId"]
        package["lead"]["segment"] = mapped_input["segment"]
        package["lead"].update(default_crm)

        if save_html_dir:
            raw_slug = package["websiteDraft"]["page_slug"]
            pid_suffix = re.sub(r"[^a-zA-Z0-9]", "", str(place_id or ""))[-8:]
            slug = f"{raw_slug}-{pid_suffix}" if pid_suffix else raw_slug
            html_file = save_html_dir / f"{slug}.html"
            html_file.write_text(package["generatedWebsiteHtml"], encoding="utf-8")
            package["savedHtmlPath"] = str(html_file.relative_to(output_path.parent))

        processed_leads.append(package)
        if place_id:
            existing_ids.add(place_id)
            existing_by_id[place_id] = package
        if clean_name:
            existing_ids.add(clean_name)
            existing_by_id[clean_name] = package
        new_added += 1

    result_payload = {
        "schemaVersion": 1,
        "lastQuery": raw_data.get("query", {}),
        "totalLeads": len(processed_leads),
        "newLeadsAdded": new_added,
        "leads": processed_leads,
    }

    fd, tmp_path = tempfile.mkstemp(
        dir=str(output_path.parent), suffix=".tmp", prefix=".leads-"
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(result_payload, handle, ensure_ascii=False, indent=2)
        os.replace(tmp_path, str(output_path))
    except Exception:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        raise
    return result_payload


def main() -> int:
    input_file = ROOT_DIR / "lead-finder" / "leads.json"
    output_file = ROOT_DIR / "unified_leads.json"
    html_out_dir = ROOT_DIR / "generated_landing_pages"

    if not input_file.exists():
        print(f"Error: Input file {input_file} not found.", file=sys.stderr)
        return 1

    print(f"Processing new leads from {input_file.relative_to(ROOT_DIR)}...")
    res = process_leads_file(input_file, output_file, html_out_dir)
    print(f"Done. Added {res['newLeadsAdded']} new leads. Total accumulated: {res['totalLeads']}.")
    print(f"Database file: {output_file.relative_to(ROOT_DIR)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
